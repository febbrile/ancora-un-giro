kit.score(function (S, T) {
  const BPM = 80, B = 60 / BPM;
  S.tempo(BPM, { t0: 0 });
  S.program('pad', 'pad', { rev: 0.65, gain: -2 });
  S.program('box', 'glock', { rev: 0.5, gain: -5, pan: 0.2 });
  S.program('mallet', 'marimba', { rev: 0.3, gain: -4, pan: -0.15 });
  S.program('bass', 'bass', { gain: -4 });
  S.program('keys', 'ep', { rev: 0.4, gain: -6 });
  S.program('vib', 'vibes', { rev: 0.6, gain: -5 });
  const C = { D: ['D3', 'F#3', 'A3', 'D4'], Bm: ['B2', 'D3', 'F#3', 'B3'], G: ['G2', 'B2', 'D3', 'G3'], A: ['A2', 'C#3', 'E3', 'A3'], Em: ['E3', 'G3', 'B3', 'E4'], Fm: ['F#2', 'A2', 'C#3', 'F#3'] };
  const ROOT = { D: 'D2', Bm: 'B1', G: 'G1', A: 'A1', Em: 'E2', Fm: 'F#2' };
  const ARP = { D: ['D5', 'A4', 'F#4', 'A4'], Bm: ['B4', 'F#4', 'D4', 'F#4'], G: ['B4', 'G4', 'D4', 'G4'], A: ['C#5', 'A4', 'E4', 'A4'], Em: ['B4', 'G4', 'E4', 'G4'], Fm: ['C#5', 'A4', 'F#4', 'A4'] };
  const bt = t => t / B;
  function sez(a, b, seq, o) {
    o = o || {};
    const b0 = Math.ceil(bt(a)), b1 = Math.floor(bt(b));
    for (let x = b0, i = 0; x + 1 < b1; x += 4, i++) {
      const c = seq[i % seq.length], len = Math.min(4, b1 - x);
      S.chord('pad', C[c], { beat: x, beats: len, vel: o.pad || 32 });
      if (o.mallet && len >= 4) S.pattern('mallet', o.mallet, { from: x, pitch: ARP[c], vel: o.mv || 50 });
      if (o.bass) S.note('bass', ROOT[c], { beat: x, beats: Math.min(3, len), vel: o.bass });
      if (o.vib && len >= 4) S.pattern('vib', 'x..x..x.', { from: x, pitch: ARP[c], vel: o.vib });
      if (o.keys) S.chord('keys', C[c].map(n => n.replace(/(\d)$/, d => String(+d + 1))), { beat: x, beats: Math.min(3.5, len), vel: o.keys });
    }
  }
  const giro = ['D', 'Bm', 'G', 'A'];
  sez(T.riassunto, T.sala, giro, { pad: 34 });
  [['A5', 1], ['F#5', 2], ['D5', 3], ['E5', 5], ['F#5', 6], ['A5', 7], ['B5', 9]].forEach(([n, b]) => S.note('box', n, { beat: b, beats: 1, vel: 42 }));
  sez(T.sala, T.incontro, ['Bm', 'G', 'Em', 'Fm'], { pad: 30, vib: 34 });
  sez(T.incontro, T.rubinetti, giro, { pad: 28, mallet: 'x...x...', mv: 40, bass: 50 });
  sez(T.rubinetti, T.cabina, ['G', 'D', 'Em', 'A'], { pad: 32, keys: 38, bass: 48 });
  sez(T.cabina, T.spiaggia, ['Bm', 'A'], { pad: 30, bass: 52 });
  S.drums({ woodblock: 'x.x.x.x.' }, { from: Math.ceil(bt(T.cabina + 2.1)), repeat: 1, vel: 40 });
  sez(T.spiaggia, T.piani, giro, { pad: 32, mallet: 'x.x.X.x.', mv: 46 });
  sez(T.piani, T.campane, ['Bm', 'G', 'A'], { pad: 32, bass: 54 });
  S.drums({ kick: 'x...x...', hat: '..o...o.' }, { from: Math.ceil(bt(T.piani)), repeat: Math.max(1, Math.floor((bt(T.campane) - bt(T.piani)) / 4) - 1), vel: 46 });
  sez(T.campane, T.secchio, ['Bm', 'Em', 'G', 'D'], { pad: 30, vib: 30 });
  sez(T.secchio, T.pesca, ['G', 'A'], { pad: 32, keys: 36 });
  sez(T.pesca, T.continua, giro, { pad: 30, mallet: 'x.x.X.x.', mv: 52, bass: 60 });
  S.drums({ kick: 'x.......', sidestick: '....x...', shaker: 'oxoxoxox' }, { from: Math.ceil(bt(T.pesca + 4)), repeat: Math.max(1, Math.floor((bt(T.continua) - bt(T.pesca + 4)) / 4) - 1), vel: 44 });
  S.fx('revswell', T.continua + 0.3, { dur: 1.4 });
  S.chord('pad', C.D, { t: T.continua + 0.3, dur: 5.4, vel: 46 });
  S.chord('keys', ['D4', 'F#4', 'A4', 'D5'], { t: T.continua + 0.3, dur: 4.5, vel: 50 });
  S.note('bass', 'D2', { t: T.continua + 0.3, dur: 4, vel: 68 });
  S.run('box', ['D5', 'F#5', 'A5', 'D6', 'F#6'], { t: T.continua - 0.3, step: 0.12, vel: 46, cresc: 10 });
  S.fx('chime', T.continua + 1.3);
  // foley
  [0, 1, 2].forEach(i => S.fx('pop', T.sala + 1.0 + i * 0.25, { vel: 34 }));
  [4.7, 5.3, 5.9, 8.6].forEach(c => S.fx('sparkle', T.sala + c, { vel: 34 }));
  [[4.6, 'sparkle'], [8.6, 'thud'], [12.6, 'sparkle']].forEach(([c, f]) => S.fx(f, T.incontro + c, { vel: 55 }));
  S.fx('ding', T.incontro + 12.9, { vel: 50 });
  S.fx('roll', T.incontro + 15.0, { dur: 1.8, vel: 44 });
  [0, 1, 2].forEach(i => { S.fx('click', T.barattoli + 1.5 + i * 0.35, { vel: 36 }); S.fx('click', T.barattoli + 4.7 + i * 0.35, { vel: 36 }); });
  S.fx('whoosh', T.rubinetti + 3.4, { dur: 1.6 }); S.fx('whoosh', T.rubinetti + 8.0, { dur: 1.5 });
  S.fx('sparkle', T.calderone + 6.4, { vel: 50 });
  S.fx('thud', T.cabina + 1.8, { vel: 44 }); S.fx('pop', T.cabina + 5.0, { vel: 50 }); S.fx('whoosh', T.cabina + 7.0, { dur: 2.4 });
  [1.0, 1.6, 1.9].forEach(c => S.fx('boing', T.spiaggia + c, { vel: 44 }));
  S.fx('whoosh', T.piani + 5.8, { dur: 1.0 });
  [8.4, 9.6, 10.8].forEach((c, i) => S.fx(i === 1 ? 'thud' : 'sparkle', T.campane + c, { vel: 52 }));
  S.chord('box', ['A5', 'C#6', 'E6'], { t: T.campane + 13.0, dur: 1.5, vel: 52 });
  S.chord('vib', ['F#4', 'A4', 'C#5', 'E5'], { t: T.campane + 14.2, dur: 3, vel: 54 });
  S.chord('box', ['E5', 'B5', 'E6'], { t: T.campane + 14.4, dur: 2, vel: 40 });
  S.fx('whoosh', T.campane + 15.0, { dur: 2.5 });
  for (let k = 0; k < 20; k++) S.fx('tick', T.secchio + 1.35 + k * 0.17, { vel: 26 });
  S.fx('roll', T.secchio + 8.6, { dur: 2.0, vel: 40 });
  S.fx('thud', T.pesca + 1.6, { vel: 50 });
  [6.0, 8.6, 17.0, 22.5].forEach(c => S.fx('pop', T.pesca + c + 0.4, { vel: 56 }));
  S.fx('ding', T.pesca + 7.9, { vel: 50 }); S.fx('click', T.pesca + 9.5, { vel: 50 });
  [11.5, 13.8, 15.8, 20.6].forEach(c => S.fx('roll', T.pesca + c, { dur: 0.8, vel: 34 }));
  S.fx('boing', T.pesca + 17.9, { vel: 60 });
  S.fx('chime', T.pesca + 23.6);
  S.master({ gain: -6, fadeOut: 1.5 });
});
